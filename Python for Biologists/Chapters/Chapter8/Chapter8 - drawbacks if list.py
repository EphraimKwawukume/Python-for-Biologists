dna = "AATGATCGATCGTACGCTGA"
all_counts = []
for base1 in ['A','G','T','C']:
    for base2 in ['A','G','T','C']:
        for base3 in ['A','G','T','C']:
            trinucleotide = base1 + base2 + base3
            count = dna.count(trinucleotide)
            print('count is: ' + str(count) + ' for ' + trinucleotide )
            all_counts.append(count)
print(all_counts)
#Firstly, the data are still incredibly sparse – the vast majority of the counts are zero.
#Secondly, the counts themselves are now disconnected from the trinucleotides. If we want to look up the count for a single trinucleotide – for example,  TGA – we first have to figure out that TGA was the 25th trinucleotide generated by our loops,before we print
print("count for TGA is " + str(all_counts[24]))
